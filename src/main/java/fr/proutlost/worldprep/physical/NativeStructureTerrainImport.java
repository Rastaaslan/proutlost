package fr.proutlost.worldprep.physical;

import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.Tag;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.util.Mth;
import net.minecraft.util.SimpleBitStorage;
import net.minecraft.world.level.dimension.DimensionType;
import net.minecraft.world.level.levelgen.Heightmap;
import net.minecraft.world.level.levelgen.structure.PoolElementStructurePiece;
import net.minecraft.world.level.levelgen.structure.Structure;
import net.minecraft.world.level.levelgen.structure.StructurePiece;
import net.minecraft.world.level.levelgen.structure.StructureStart;
import net.minecraft.world.level.levelgen.structure.pieces.PiecesContainer;
import net.minecraft.world.level.levelgen.structure.pools.JigsawJunction;
import net.minecraft.world.level.levelgen.structure.pools.StructureTemplatePool;
import net.minecraft.world.level.storage.LevelResource;

import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/** Explicit one-time import adaptation for an existing painted map.
 * The registered generator still creates the real native pieces. Only the four
 * installed, rigid, surface-projected YUNG models are supported here. Their
 * complete piece graph is translated by the difference between persisted and
 * seed surface at the exact reference column used by YUNG's start projection.
 * No biome is changed, no block is written, no chunk is generated by this class.
 */
final class NativeStructureTerrainImport {
    static final String POLICY="EXPLICIT_EXISTING_TERRAIN_IMPORT_V1";
    static final Set<String> SURFACE_MODELS=Set.of(
        "betterdeserttemples:desert_temple","betterjungletemples:jungle_temple",
        "betterwitchhuts:witch_hut","betterwitchhuts:witch_circle");

    record Adjustment(String policy,NativeRegistryStructurePass.Bounds originalBounds,
            NativeRegistryStructurePass.Bounds placedBounds,int verticalOffset,
            Integer seedSurface,Integer persistedSurface,Integer sampleX,Integer sampleZ,
            String seedHeightmap,String persistedHeightmap,int validatedPieces,int translatedJunctions) {
        static Adjustment unchanged(NativeRegistryStructurePass.Bounds bounds) {
            return new Adjustment("NATIVE_VERTICAL_LAYOUT_UNCHANGED",bounds,bounds,0,
                null,null,null,null,null,null,0,0);
        }
    }
    record Result(StructureStart start,Adjustment adjustment) {}

    static Result apply(ServerLevel level,Structure structure,StructureStart start,String registryId,
                        NativeRegistryStructurePass.Conditions conditions)throws IOException {
        var original=NativeRegistryStructurePass.Bounds.from(start.getBoundingBox());
        if(conditions!=NativeRegistryStructurePass.Conditions.IMPORT_EXISTING_TERRAIN)
            return new Result(start,Adjustment.unchanged(original));
        if(!SURFACE_MODELS.contains(registryId))
            throw new IOException("Existing-terrain import supports only the four qualified surface models: "+registryId);
        if(start.getPieces().isEmpty())throw new IOException("Missing native start piece for terrain import");
        var first=start.getPieces().getFirst().getBoundingBox();
        // Match installed YungsApi 5.1.9 JigsawManager's integer division exactly.
        int x=(first.minX()+first.maxX())/2,z=(first.minZ()+first.maxZ())/2;
        var region=DimensionType.getStorageFolder(level.dimension(),
            level.getServer().getWorldPath(LevelResource.ROOT)).resolve("region");
        CompoundTag chunk=ReadOnlyChunkNbt.read(region,x>>4,z>>4);
        int persisted=surfaceFromNbt(chunk,x,z,level.getMinBuildHeight(),level.getMaxBuildHeight());
        var source=level.getChunkSource();
        int seeded=source.getGenerator().getFirstFreeHeight(x,z,Heightmap.Types.WORLD_SURFACE_WG,
            level,source.randomState());
        int offset;
        try{offset=Math.subtractExact(persisted,seeded);}
        catch(ArithmeticException bad){throw new IOException("Surface import height difference overflow",bad);}
        var expected=translateBounds(original,offset,level.getMinBuildHeight(),level.getMaxBuildHeight());
        int junctionCount=translatePieces(start.getPieces(),offset,level.getMinBuildHeight(),level.getMaxBuildHeight());
        // StructureStart caches its bounding box; a fresh wrapper is mandatory after moving pieces.
        var shifted=new StructureStart(structure,start.getChunkPos(),start.getReferences(),
            new PiecesContainer(start.getPieces()));
        var actual=NativeRegistryStructurePass.Bounds.from(shifted.getBoundingBox());
        if(!expected.equals(actual))throw new IOException("Native surface import did not preserve rigid geometry");
        return new Result(shifted,new Adjustment(POLICY,original,actual,offset,seeded,persisted,x,z,
            "WORLD_SURFACE_WG","MOTION_BLOCKING_NO_LEAVES",start.getPieces().size(),junctionCount));
    }

    /** Decode actual persisted collision-ground height, including negative build-min offset.
     * WORLD_SURFACE includes grass and flowers after ecology; use the persisted
     * MOTION_BLOCKING_NO_LEAVES map so imported floors do not float above plants.
     * A missing/malformed heightmap is an error, never a seed-height fallback. */
    static int surfaceFromNbt(CompoundTag chunk,int x,int z,int minY,int maxYExclusive)throws IOException {
        if(minY>=maxYExclusive||!chunk.contains("Heightmaps",Tag.TAG_COMPOUND))
            throw new IOException("Existing surface heightmap absent");
        var maps=chunk.getCompound("Heightmaps");
        if(!maps.contains("MOTION_BLOCKING_NO_LEAVES",Tag.TAG_LONG_ARRAY))
            throw new IOException("Persisted MOTION_BLOCKING_NO_LEAVES heightmap absent");
        int height=maxYExclusive-minY;
        try {
            var storage=new SimpleBitStorage(Mth.ceillog2(height+1),256,maps.getLongArray("MOTION_BLOCKING_NO_LEAVES"));
            int relative=storage.get((x&15)+16*(z&15));
            if(relative<=0||relative>height)throw new IOException("Persisted surface column outside build range");
            return Math.addExact(minY,relative);
        }catch(IllegalArgumentException|ArithmeticException|SimpleBitStorage.InitializationException malformed) {
            throw new IOException("Invalid persisted surface heightmap",malformed);
        }
    }

    static NativeRegistryStructurePass.Bounds translateBounds(NativeRegistryStructurePass.Bounds b,
            int offset,int minY,int maxYExclusive)throws IOException {
        try {
            int low=Math.addExact(b.minY(),offset),high=Math.addExact(b.maxY(),offset);
            if(low<minY||high>=maxYExclusive)
                throw new IOException("Translated native structure crosses build limits; no clipping permitted");
            return new NativeRegistryStructurePass.Bounds(b.minX(),low,b.minZ(),b.maxX(),high,b.maxZ());
        }catch(ArithmeticException overflow){throw new IOException("Native translation overflow",overflow);}
    }

    /** Validate all pieces before moving any; keep jigsaw metadata in the same coordinate frame. */
    static int translatePieces(List<? extends StructurePiece> pieces,int offset,int minY,int maxYExclusive)throws IOException {
        var junctions=new ArrayList<List<JigsawJunction>>(pieces.size());
        var expectedBounds=new ArrayList<NativeRegistryStructurePass.Bounds>(pieces.size());
        var expectedPositions=new ArrayList<net.minecraft.core.BlockPos>(pieces.size());
        int junctionCount=0;
        for(var piece:pieces) {
            if(!(piece instanceof PoolElementStructurePiece pool)
                    ||pool.getElement().getProjection()!=StructureTemplatePool.Projection.RIGID)
                throw new IOException("Unqualified non-rigid surface piece cannot be terrain-imported");
            expectedBounds.add(translateBounds(NativeRegistryStructurePass.Bounds.from(piece.getBoundingBox()),offset,minY,maxYExclusive));
            var moved=new ArrayList<JigsawJunction>(pool.getJunctions().size());
            try {
                for(var j:pool.getJunctions())moved.add(new JigsawJunction(j.getSourceX(),
                    Math.addExact(j.getSourceGroundY(),offset),j.getSourceZ(),j.getDeltaY(),j.getDestProjection()));
                int expectedY=Math.addExact(pool.getPosition().getY(),offset);
                expectedPositions.add(new net.minecraft.core.BlockPos(pool.getPosition().getX(),expectedY,pool.getPosition().getZ()));
            }catch(ArithmeticException overflow){throw new IOException("Native piece metadata translation overflow",overflow);}
            junctions.add(moved);junctionCount+=moved.size();
        }
        for(int i=0;i<pieces.size();i++) {
            var piece=(PoolElementStructurePiece)pieces.get(i);
            piece.move(0,offset,0);
            piece.getJunctions().clear();piece.getJunctions().addAll(junctions.get(i));
            if(!piece.getPosition().equals(expectedPositions.get(i))
                    ||!NativeRegistryStructurePass.Bounds.from(piece.getBoundingBox()).equals(expectedBounds.get(i)))
                throw new IOException("Native rigid piece position/bounds translation mismatch");
            if(piece.getJunctions().size()!=junctions.get(i).size())
                throw new IOException("Native rigid piece junction count mismatch");
            for(int j=0;j<junctions.get(i).size();j++) {
                var actual=piece.getJunctions().get(j);var expected=junctions.get(i).get(j);
                // Vanilla JigsawJunction.equals omits sourceGroundY, so compare each field explicitly.
                if(actual.getSourceX()!=expected.getSourceX()||actual.getSourceGroundY()!=expected.getSourceGroundY()
                        ||actual.getSourceZ()!=expected.getSourceZ()||actual.getDeltaY()!=expected.getDeltaY()
                        ||actual.getDestProjection()!=expected.getDestProjection())
                    throw new IOException("Native rigid piece junction translation mismatch");
            }
        }
        return junctionCount;
    }
    private NativeStructureTerrainImport(){}
}
